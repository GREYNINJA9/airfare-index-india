"""Pipeline Ingestion Service for Scraped Flight/Fare Payloads.

Bridges raw and normalized scraper outputs (such as JSON files generated by
``cleartrip_ui.py`` in ``data/normalized/cleartrip/``) into the core SIH 26056
pipeline:

    Scraper / Normalized JSON
                ↓
    Payload Extractor & Raw Record Builder
                ↓
    Common Pipeline: Validation → Cleaning → Normalization → Deduplication
                ↓
    PostgreSQL Database Persistence (fares table, ON CONFLICT DO NOTHING)
                ↓
    Index Engine Recalculation (PSD weights, Laspeyres, Jevons)
                ↓
    Cache Invalidation (Real-time update across FastAPI & Web Dashboard)
"""

from __future__ import annotations

